"""Turn every run in runs/ into the ablation table that goes in the README.

The table is generated, never hand-typed. If a number in the README is stale, this
script regenerates it; if a run is missing, the row is missing. That is the point —
a README claim you cannot regenerate is a README claim you should not make.

    python eval/report.py --out RESULTS.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

COLUMNS = [
    ("config", lambda m: m["config"]),
    ("n", lambda m: m["n"]),
    ("recall@5", lambda m: _g(m, "retrieval", "recall@5", "mean")),
    ("nDCG@5", lambda m: _g(m, "retrieval", "ndcg@5", "mean")),
    ("MRR", lambda m: _g(m, "retrieval", "mrr", "mean")),
    ("intent F1", lambda m: m["routing"]["intent_macro_f1"]),
    ("slot acc", lambda m: _g(m, "routing", "slot_accuracy", "mean")),
    ("grounded", lambda m: _g(m, "generation", "groundedness", "mean")),
    ("halluc. id", lambda m: m["generation"]["hallucinated_id_rate"]),
    ("viol.", lambda m: m["generation"]["constraint_violation_rate"]),
    ("llm calls", lambda m: _g(m, "systems", "llm_calls", "mean")),
    ("p50 ms", lambda m: _g(m, "systems", "latency_ms", "median")),
]


def _g(m: dict, *path: str):
    cur = m
    for key in path:
        cur = cur.get(key, {}) if isinstance(cur, dict) else {}
    return cur if not isinstance(cur, dict) else "—"


def collect(runs_dir: Path) -> list[dict]:
    out = []
    for metrics_file in sorted(runs_dir.glob("*/metrics.json")):
        try:
            out.append(json.loads(metrics_file.read_text()) | {"_dir": metrics_file.parent.name})
        except json.JSONDecodeError:
            continue
    return out


def latest_per_config(runs: list[dict]) -> list[dict]:
    """Directory names start with a UTC timestamp, so the last one wins."""
    best: dict[str, dict] = {}
    for r in sorted(runs, key=lambda r: r["_dir"]):
        best[r["config"]] = r
    return list(best.values())


def render(runs: list[dict]) -> str:
    header = "| " + " | ".join(c[0] for c in COLUMNS) + " |"
    sep = "|" + "|".join("---" for _ in COLUMNS) + "|"
    lines = [header, sep]
    for m in runs:
        cells = []
        for _, fn in COLUMNS:
            try:
                v = fn(m)
            except (KeyError, TypeError):
                v = "—"
            cells.append(f"{v:.3f}" if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=str(ROOT / "runs"))
    ap.add_argument("--out", default=str(ROOT / "RESULTS.md"))
    ap.add_argument("--all", action="store_true", help="every run, not just the latest per config")
    args = ap.parse_args()

    runs = collect(Path(args.runs))
    if not runs:
        print("no runs found — run `make eval` first")
        return
    rows = runs if args.all else latest_per_config(runs)
    prov = rows[-1].get("provenance", {})
    body = (
        "# Results\n\n"
        "Generated by `eval/report.py`. Do not edit by hand.\n\n"
        f"{render(rows)}\n\n"
        f"_git {prov.get('git_sha', '?')}"
        f"{' (dirty)' if prov.get('git_dirty') else ''} · "
        f"python {prov.get('python', '?')} · {prov.get('timestamp', '')}_\n"
    )
    Path(args.out).write_text(body)
    print(body)


if __name__ == "__main__":
    main()
